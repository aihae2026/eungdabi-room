import crypto from "node:crypto";
import fs from "node:fs";
import vm from "node:vm";
import path from "node:path";
import { fileURLToPath } from "node:url";

const projectRoot = fs.realpathSync(path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..'));
const inputPath = path.join(projectRoot, 'assets/institutions.js');
const requestedDirectory = process.env.SEED_OUTPUT_DIR;
if (!requestedDirectory || !path.isAbsolute(requestedDirectory)) throw new Error('Set SEED_OUTPUT_DIR to a new absolute directory OUTSIDE this project and all public/synced folders.');
const parent = fs.realpathSync(path.dirname(requestedDirectory));
const outputDirectory = path.join(parent, path.basename(requestedDirectory));
const relative = path.relative(projectRoot, outputDirectory);
if (!relative || (!relative.startsWith('..' + path.sep) && !path.isAbsolute(relative))) throw new Error('Seed output must be outside the project.');
if (fs.existsSync(outputDirectory)) throw new Error('Choose a NEW output directory; existing seed files will not be overwritten.');
const outputPath = path.join(outputDirectory, 'seed.sql');
const credentials = institutions => institutions.map(item => ({ institutionCode: item.code, adminPassword: crypto.randomBytes(24).toString('base64url'), intakePassword: crypto.randomBytes(24).toString('base64url') }));

function sql(value) {
  if (value === null || value === undefined) return "null";
  return `'${String(value).replace(/'/g, "''")}'`;
}

function passwordRecord(password) {
  const salt = crypto.randomBytes(16).toString("hex");
  const hash = crypto.pbkdf2Sync(password, salt, 100000, 32, "sha256").toString("hex");
  return { salt, hash };
}

const sandbox = { window: {} };
vm.createContext(sandbox);
vm.runInContext(fs.readFileSync(inputPath, "utf8"), sandbox);

const centralInstitution = {
  code: "SAMPLECENTRAL",
  name: "가상 중앙운영기관",
  sido: "가상전국",
  sigungu: "중앙운영기관",
  type: "central",
  parentCode: null,
};
// Match institutions_regional_sigungu_check without changing the source fixture.
const institutions = [centralInstitution, ...(sandbox.window.INSTITUTION_MASTER || [])]
  .map(item => ({ ...item, sigungu: item.type === 'regional' ? '' : item.sigungu }));
const issued = credentials(institutions);
const lines = [
  "-- Generated by scripts/generate-supabase-seed.mjs",
  "begin;",
  "",
  "insert into public.institutions (code, name, sido, sigungu, type, parent_code, managed_target_count, active)",
  "values",
  institutions
    .map((item) => `  (${sql(item.code)}, ${sql(item.name)}, ${sql(item.sido)}, ${sql(item.sigungu)}, ${sql(item.type)}, ${sql(item.parentCode)}, ${item.type === "central" ? 0 : 250}, true)`)
    .join(",\n") +
    "\non conflict (code) do update set\n  name = excluded.name,\n  sido = excluded.sido,\n  sigungu = excluded.sigungu,\n  type = excluded.type,\n  parent_code = excluded.parent_code,\n  updated_at = now();",
  "",
  "insert into public.agency_accounts (institution_code, password_hash, password_salt, intake_password_hash, intake_password_salt, active)",
  "values",
  institutions
    .map((item, i) => {
      const { salt, hash } = passwordRecord(issued[i].adminPassword);
      const intake = passwordRecord(issued[i].intakePassword);
      return `  (${sql(item.code)}, ${sql(hash)}, ${sql(salt)}, ${sql(intake.hash)}, ${sql(intake.salt)}, true)`;
    })
    .join(",\n") +
    "\non conflict (institution_code) do nothing;",
  "",
  "commit;",
  "",
];

fs.mkdirSync(outputDirectory, { mode: 0o700 });
fs.writeFileSync(outputPath, lines.join("\n"), { encoding: 'utf8', mode: 0o600, flag: 'wx' });
fs.writeFileSync(path.join(outputDirectory, 'seed-credentials.json'), JSON.stringify(issued, null, 2), { encoding: 'utf8', mode: 0o600, flag: 'wx' });
console.log(`Created private seed files for ${institutions.length} NEW sample institutions. Passwords are not printed. This does not rotate existing accounts. Protect the output folder and delete both files after secure delivery and import.`);
